import assert from 'node:assert/strict';
import {calculatePrivateSwing,calculatePrivatePickets,fullSwingPricingInput} from './kd-private-pricing.mjs';
// All monetary inputs here are synthetic. Never replace with the business workbook.
const frame=Object.fromEntries(['mainPrice','innerPrice','stripPrice','hingePrice','lockPrice','paintPrice','cutDisc','grindDisc','wire','gas','rent','rearPrice','rearPaintArea','pins','mainPaintArea','innerPaintArea','hingePlate','wageGate','wageWicket','wageRound','frameMarkup'].map(k=>[k,1]));
Object.assign(frame,{mainPrice:100,innerPrice:50,stripPrice:50,paintPrice:100,mainPaintArea:.2,innerPaintArea:.08,rearPaintArea:.12,wageGate:1000,wageWicket:500,wageRound:100,frameMarkup:1.5});
const rates={frame,fill:{sheetPrice:100,sheetScrewPrice:1,sheetGateLabor:100,sheetWicketLabor:100,fillMarkup:1.2},extras:{post80x80:1000,installset:1000}};
const bundle={kind:'frames',approved:true,revision:'test-fixture-1',rates};
const draft={hinges:true,lock:true,bolts:true,gapMode:'excel'};
const basic=calculatePrivateSwing(draft,bundle),filled=calculatePrivateSwing({...draft,fill:'sheet',postType:'80x80',installation:'set'},bundle);
assert(basic.quote.prices.total>0);
assert(filled.quote.prices.total>basic.quote.prices.total);
assert.equal(filled.quote.prices.posts,3000);
assert.equal(filled.quote.prices.installation,1000);
assert.equal(filled.canReleaseProduction,false);
assert.equal(filled.quote.prices.gateRetail+filled.quote.prices.wicketRetail,filled.quote.prices.productRetail);
for(const patch of [{product:'gate'},{product:'wicket'},{hinges:false},{lock:false},{bolts:false},{posts:true},{diagonal:'25x25x1.5'}])assert.throws(()=>fullSwingPricingInput({...draft,...patch}));
assert.throws(()=>calculatePrivateSwing(draft,{...bundle,approved:false}));
assert.throws(()=>calculatePrivateSwing(draft,{...bundle,rates:{frame:{}}}));
assert(!JSON.stringify(filled).match(/"owner"|"wage"|"productCost"|"profit"/));
const pr=Object.fromEntries(['picketSinglePrice','picketDoublePrice','tube40Price','post60Price','post80Price','post100Price','postMetalMarkupPercent','postPaintMarkupPercent','paintPrice','workVerticalSingle','workVerticalDouble','workHorizontalDouble','postInstallPrice','screwPrice','markupPercent','measurerPercent'].map(k=>[k,10]));
const pb={kind:'pickets',approved:true,revision:'test-fixture-2',rates:pr};
const side={fit:true,lengthMm:12000,heightMm:1800};
const fence={version:2,sides:{'А':side,'Б':side},corners:{'АБ':true}};
const p=calculatePrivatePickets(fence,pb);
assert(p.quote.total>0);
assert(calculatePrivatePickets({...fence,corners:{}},pb).quote.total>p.quote.total);
assert.throws(()=>calculatePrivatePickets({...fence,sides:{'А':{...side,fit:false}},corners:{}},pb));
assert.throws(()=>calculatePrivatePickets({...fence,sides:{'А':{...side,gateMm:3400,openingStartMm:1000}},corners:{}},pb));
assert.throws(()=>calculatePrivatePickets(fence,{...pb,rates:{}}));
assert(!JSON.stringify(p).match(/"costs"|"quantities"|"profit"|"owner"/));
assert.equal(p.canIssue,false);
assert.equal(p.canReleaseProduction,false);
console.log('Private swing and picket adapter: synthetic full kit, shared posts, incomplete rates/options and release locks passed');
