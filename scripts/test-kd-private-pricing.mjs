import assert from 'node:assert/strict';
import {calculatePrivateSwing,calculatePrivatePickets,fullSwingPricingInput} from './kd-private-pricing.mjs';
// All monetary inputs here are synthetic. Never replace with the business workbook.
const frame=Object.fromEntries(['mainPrice','innerPrice','stripPrice','hingePrice','lockPrice','paintPrice','cutDisc','grindDisc','wire','gas','rent','rearPrice','rearPaintArea','pins','mainPaintArea','innerPaintArea','hingePlate','wageGate','wageWicket','wageRound','frameMarkup'].map(k=>[k,1]));
Object.assign(frame,{mainPrice:100,innerPrice:50,stripPrice:50,paintPrice:100,mainPaintArea:.2,innerPaintArea:.08,rearPaintArea:.12,wageGate:1000,wageWicket:500,wageRound:100,frameMarkup:1.5});
const rates={frame,fill:{sheetPrice:100,sheetScrewPrice:1,sheetGateLabor:100,sheetWicketLabor:100,fillMarkup:1.2},extras:{post80x80:1000,installset:1000}};
const bundle={kind:'frames',approved:true,revision:'test-fixture-1',rates};
const draft={hinges:true,lock:true,bolts:true,gapMode:'excel'};
const basic=calculatePrivateSwing(draft,bundle),filled=calculatePrivateSwing({...draft,fill:'sheet',postType:'80x80',installation:'set'},bundle);
assert(basic.quote.prices.total>0);
assert(filled.quote.prices.total>basic.quote.prices.total);
assert.equal(filled.quote.prices.posts,3000);
assert.equal(filled.quote.prices.installation,1000);
assert.equal(filled.canReleaseProduction,false);
assert.equal(filled.quote.prices.gateRetail+filled.quote.prices.wicketRetail,filled.quote.prices.productRetail);
for(const patch of [{product:'gate'},{product:'wicket'},{hinges:false},{lock:false},{bolts:false},{posts:true},{diagonal:'25x25x1.5'}])assert.throws(()=>fullSwingPricingInput({...draft,...patch}));
assert.throws(()=>calculatePrivateSwing(draft,{...bundle,approved:false}));
assert.throws(()=>calculatePrivateSwing(draft,{...bundle,rates:{frame:{}}}));
assert(!JSON.stringify(filled).match(/"owner"|"wage"|"productCost"|"profit"/));
const pr=Object.fromEntries(['picketSinglePrice','picketDoublePrice','tube40Price','post60Price','post80Price','post100Price','postMetalMarkupPercent','postPaintMarkupPercent','paintPrice','workVerticalSingle','workVerticalDouble','workHorizontalDouble','postInstallPrice','screwPrice','markupPercent','measurerPercent'].map(k=>[k,10]));
const pb={kind:'pickets',approved:true,revision:'test-fixture-2',rates:pr};
const side={fit:true,lengthMm:12000,heightMm:1800};
const fence={version:2,sides:{'А':side,'Б':side},corners:{'АБ':true}};
const p=calculatePrivatePickets(fence,pb);
assert(p.quote.total>0);
assert(calculatePrivatePickets({...fence,corners:{}},pb).quote.total>p.quote.total);
assert.throws(()=>calculatePrivatePickets({...fence,sides:{'А':{...side,fit:false}},corners:{}},pb));
assert.throws(()=>calculatePrivatePickets({...fence,sides:{'А':{...side,gateMm:3400,openingStartMm:1000}},corners:{}},pb));
assert.throws(()=>calculatePrivatePickets(fence,{...pb,rates:{}}));
assert(!JSON.stringify(p).match(/"costs"|"quantities"|"profit"|"owner"/));
assert.equal(p.canIssue,false);
assert.equal(p.canReleaseProduction,false);
console.log('Private swing and picket adapter: synthetic full kit, shared posts, incomplete rates/options and release locks passed');

const {serialFrameParts,serialFramePrivateQuote}=await import('./kd-private-serial-frame.mjs');
const sr={kind:'serialFrames',policy:'serial-40x25-v1',approved:true,revision:'synthetic-serial',rates:{...frame,post80x80:1000,hingePrice:200,hingePlate:20,lockPrice:1000,pins:500}};
const bare={gapMode:'excel'};
const gate=serialFrameParts({...bare,product:'gate'}),wicket=serialFrameParts({...bare,product:'wicket'}),kit=serialFrameParts(bare);
assert.equal(gate.main.count,4);
assert.equal(wicket.main.count,2);
assert.equal(kit.main.count,6);
assert.equal(wicket.rearStock,0);
assert.equal(wicket.gateMm,0);
assert.equal(gate.wicketMm,0);
assert(Math.abs(gate.gateMm+wicket.wicketMm-kit.main.actualMm)<1e-7);
const g=serialFramePrivateQuote({...bare,product:'gate'},sr);
const w=serialFramePrivateQuote({...bare,product:'wicket'},sr);
assert(g.prices.total>w.prices.total);
assert(serialFramePrivateQuote({...bare,product:'gate',hinges:true,bolts:true},sr).prices.total>g.prices.total);
assert(serialFramePrivateQuote({...bare,product:'wicket',lock:true},sr).prices.total>w.prices.total);
assert(serialFramePrivateQuote({...bare,product:'wicket',paint:true},sr).prices.total>w.prices.total);
const withPosts=serialFramePrivateQuote({...bare,product:'gate',posts:true,privateCost:1234},sr);
assert.equal(withPosts.prices.posts,2000);
assert.equal(withPosts.prices.total-g.prices.total,2000);
assert(!JSON.stringify(withPosts).includes('privateCost'));
assert.equal(withPosts.canIssue,false);
for(const patch of [{product:'gate',lock:true},{product:'wicket',bolts:true},{fill:'sheet'},{wicketType:'builtIn'},{profile:'60x40x2'},{gateWidthMm:5400},{link:true}])assert.throws(()=>serialFramePrivateQuote({...bare,...patch},sr));
assert.throws(()=>serialFramePrivateQuote(bare,{...sr,approved:false}));
assert.throws(()=>serialFramePrivateQuote(bare,{...sr,rates:{}}));
console.log('Proposed serial frame: separate procurement, optional hardware, paint, posts and approval gates passed');

const {privateCanopyQuote,CANOPY_RATE_KEYS}=await import('./kd-private-canopy.mjs');
const cr=Object.fromEntries(CANOPY_RATE_KEYS.map(k=>[k,100]));
Object.assign(cr,{markup:25,separateMarkup:40,ownerMount:0});
const cb={kind:'canopy',policy:'legacy-canopy-installed-v1',approved:true,revision:'synthetic-canopy',rates:cr};
const scope={installationScope:'included'};
const base=privateCanopyQuote({},cb,scope);
assert.equal(base.prices.product+base.prices.installation,base.prices.total);
assert(base.prices.total>0);
assert(base.prices.installation>0);
assert(privateCanopyQuote({paint:false},cb,scope).prices.total<base.prices.total);
assert(privateCanopyQuote({existingPosts:2},cb,scope).prices.total<base.prices.total);
assert(privateCanopyQuote({beamsExisting:true},cb,scope).prices.total<base.prices.total);
for(const coverage of ['Профнастил','Без покрытия'])assert(privateCanopyQuote({coverage},cb,scope).prices.total>0);
assert.throws(()=>privateCanopyQuote({},cb,{installationScope:'excluded'}));
assert.throws(()=>privateCanopyQuote({},cb));
assert.throws(()=>privateCanopyQuote({}, {...cb,rates:{...cr,poly:undefined}},scope));
assert.throws(()=>privateCanopyQuote({widthMm:7000},cb,scope));
assert.throws(()=>privateCanopyQuote({existingPosts:100},cb,scope));
assert.throws(()=>privateCanopyQuote({}, {...cb,approved:false},scope));
assert(!JSON.stringify(base).match(/"ownerMount"|"actualExpenses"|"profit"|"rates"/));
assert.equal(base.canIssue,false);
assert.equal(base.canReleaseProduction,false);
assert.equal(base.engineeringPending,true);
console.log('Private canopy: complete synthetic rates, mounting scope, roof options, missing rates and release locks passed');
